# La función str() sirve para convertir un valor en texto (cadena de caracteres).
# str(valor) convierte el valor dado en una cadena de caracteres.
numero = 123
texto = str(numero)  # Convierte el número 123 en la cadena "123"
print(texto)         # Imprime: 123
print(type(texto))   # Imprime: <class 'str'>       